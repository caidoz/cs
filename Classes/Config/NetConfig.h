#pragma once

#ifndef _CONFIG_NET_H_
#define _CONFIG_NET_H_

//=============================================================================
// 서버 접속 설정
//
// BuildConfig.h 에 두지 않는다. 그쪽은 Definitions.xlsx 에서 자동 생성되는
// 파일이라 여기 적은 것이 다음 생성 때 날아간다. ContentConfig.h 가 같은
// 이유로 따로 있다.
//=============================================================================

//---- 게임 서버 ----
//
// 끝에 / 를 붙이지 않는다. 여기에 엔드포인트 셋이 있어야 한다.
//
//     POST <베이스>/v1/login
//     GET  <베이스>/v1/save
//     POST <베이스>/v1/save
//
// 비워 두면 네트워크를 안 탄다. 대신 예전처럼 클라이언트 안의 임시 서버가
// 쓰기 가능 경로의 serverdb.dat 으로 처리한다. 서버 없이 게임을 돌릴 때,
// 그리고 서버를 붙이기 전후를 견줘볼 때 그렇게 쓴다.
//
// 즉 이 줄이 비어 있는 동안에는 예전과 한 글자도 다르게 동작하지 않는다.
//
//     #define NET_SERVER_URL "https://api.example.com"
//
// https 를 쓸 것. http 로 두면 안드로이드와 iOS가 기본 설정에서 막는다.
// 개발 중에 평문으로 시험하려면 win32 에서만 하면 된다.
//
// 서버 없이 돌려보고 싶으면 이 줄을 "" 로 비우면 된다. 그러면 예전처럼
// 클라이언트 안의 임시 서버가 serverdb.dat 으로 처리한다.
#define NET_SERVER_URL "https://api.bigpixel.kr"

//---- 게스트 열쇠를 담아둘 파일 ----
//
// 첫 실행에 UUID 를 하나 만들어 여기 넣는다. 이것이 계정의 유일한 열쇠다.
// 유출되면 계정을 통째로 잃는다 — schema.sql 의 account.guest_key 주석이
// 이미 그렇게 경고하고 있다.
//
// 3단계에서 구글·애플 연동이 붙고 나면 이 열쇠는 세션 토큰을 받아오는
// 수단으로 물러난다. 그때 바뀌는 것은 NetAuthHeader() 하나다.
#define NET_GUESTKEYFILE	"guestkey.txt"

//---- 약관 게이트를 건너뛴다 ----
//
// 1 이면 약관 동의를 안 받고 곧바로 로그인한다.
//
// 화면이 아직 없어서 동의를 받을 방법이 없다. 그대로 두면 부팅이 약관에서
// 멈춰 검은 화면이 된다. 화면을 붙이기 전까지 게임을 돌려보려면 켜둔다.
//
// ★ 출시 전에 반드시 0 으로 되돌릴 것.
//
//   동의 없이 계정을 만드는 것은 개인정보 처리에 해당한다. 게스트 계정도
//   기기가 만든 UUID 를 서버에 남긴다. 이 줄이 1 인 채로 나가면 그것을
//   동의 없이 하게 된다.
#define NET_SKIP_TERMS 1

//---- 약관 전문 주소 ----
//
// CDN 의 terms.tsv 가 이 값을 덮는다. 여기 적어두는 것은 못 읽었을 때를
// 위해서다 — 설정 메뉴의 약관 버튼은 오프라인에서도 눌린다.
#define NET_TERMS_URL	"https://cdn.bigpixel.kr/terms.html"
#define NET_PRIVACY_URL	"https://cdn.bigpixel.kr/privacy.html"

//확률 정보. 게임산업법이 게임 안과 밖 양쪽에 알리라고 한다.
//표는 tools/content/gacha_rates.py 가 확률 데이터에서 직접 뽑아 만든다.
#define NET_RATES_URL	"https://cdn.bigpixel.kr/rates.html"

//---- 기다리는 시간 ----
//
// 부팅은 길게 준다. 여기서 실패하면 오프라인 캐시로 시작해야 하는데,
// 지하철에서 신호가 오락가락할 때 성급하게 포기하면 멀쩡한 세이브를 두고
// 캐시로 시작해 버린다.
#define NET_TIMEOUT_SEC		15

#endif
