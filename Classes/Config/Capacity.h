#pragma once

#ifndef _CONFIG_CAPACITY_H_
#define _CONFIG_CAPACITY_H_

//=============================================================================
// 콘텐츠 용량
//
// [왜 필요한가]
// 앱을 새로 올리지 않고 CDN 팩만 갈아끼워 몬스터나 동료를 추가하려면, ID
// 구간이 콘텐츠 "개수"에 붙어 있으면 안 된다. 지금은 이렇게 돼 있다.
//
//     TEXT_MONSTERNAME_START = 127,
//     TEXT_ITEMNAME_START = TEXT_MONSTERNAME_START + TOTALENEMY,
//
// 몬스터를 하나 늘리면 TOTALENEMY 가 432가 되고, 그 뒤 텍스트 ID 9천여 개가
// 전부 1씩 밀린다. 옛 클라이언트는 새 팩의 몬스터 이름 자리에서 아이템
// 이름을 읽게 된다. 팩으로는 절대 못 고친다.
//
// [어떻게 푸는가]
// "용량"과 "개수"를 가른다.
//
//     용량 = 여기 적은 CAP_*. 컴파일 상수다. ID 구간과 배열 크기를 잡는다.
//     개수 = 지금 실제로 몇 개인가. 런타임 값이고 팩이 정한다.
//            루프와 범위검사가 쓴다.
//
// 용량 안에서 늘어나는 한 ID는 그대로다. 팩만 갈아끼우면 된다.
//
// [용량을 늘리려면]
// 앱을 새로 올려야 한다. 그러니 처음에 넉넉히 잡는다. 값이 비싼 쪽은
// CAP_ENEMY 와 CAP_MAP 인데, 텍스트 ID 구간을 각각 4번, 1번 잡아먹고
// TEXT_LENGTH 가 늘면 sameFontLabelArr 같은 큰 배열이 같이 는다.
//=============================================================================

enum {
	CAP_ENEMY  = 512,	//현재 431. 몬스터/NPC 종류
	CAP_CREW   = 96,	//현재 64.  동료 종류
	CAP_SKILL  = 2048,	//현재 1374
	CAP_CASTLE = 32,	//현재 19.  성(지역)
	CAP_MAP    = 512,	//현재 425

	//cmf = 모션 묶음. 캐릭터 하나가 하나씩 쓴다.
	CAP_CMF      = 256,	//현재 123
	CAP_CMF_HERO = 8,	//현재 3. cmfHeroLoop 전용
};

#endif
