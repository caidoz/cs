//---- 진행 속도 ----
//
// 무기 한 자루를 얻는 데 걸리는 스테이지 수. 몬스터 체력 곡선이 이 값을
// 기준으로 한 계단씩 오른다. 무기 표(itemValue) 와 짝이므로 한쪽만 바꾸면
// 안 된다.
#define WAVE_STAGE_PER_TIER		500

//---- 몬스터 체력 ----
//
// [왜 등비인가]
// 전에는 등차였다.
//
//     100 * (waveIdx + 10) * (100 + ADDHP) / 10
//
// 1스테이지 10,000 에서 1000스테이지 1,009,000 까지 x100.9 로 곧게 올라갔다.
// 그런데 주인공의 힘은 무기가 정하고 무기는 등비다(x1.145 / 자루). 모양이
// 다른 두 곡선은 어디선가 반드시 엇갈린다. 초반은 벽이고 후반은 시시해진다.
//
// [기준점]
// 튜토리얼이 답을 들고 있었다.
//
//     TUTORIAL_WAVEIDX_3RD  체력 100  "하트 3배 베팅 공격에만 죽도록"
//     TUTORIAL_BOSS_HP      300       "동료 3중첩 강공격 한 방에"
//
// betHeart[2] 가 3 이므로 그때 주인공의 한 대는 33 안팎이라는 뜻이다.
// 첫 검이 10 이니 실제로 때리는 값은 무기값의 3배쯤 된다(스탯과 동료).
//
// 그래서 첫 몬스터를 "보통 공격 열 대"로 잡는다. 33 * 10 = 330. 튜토리얼
// 보스(300)와 비슷한 자리다. 지금 값 10,000 은 여기서 30배가 넘었다.
#define WAVE_HP_BASE			330

// [계단 크기]
// 무기 한 자루(500스테이지)마다 체력이 몇 배가 되는가.
//
// 주인공이 35자루를 다 모으는 동안 얻는 배수를 어림하면
//
//     무기      x100   (10 -> 999)
//     장갑      x1.8   (공격력 +80%)
//     강화      x1.5
//     ------------------
//     합계      x270
//
// 이걸 35계단에 나누면 270^(1/35) = 1.174 다. 즉 체력이 이 속도보다 빠르면
// 아무리 좋은 장비를 껴도 영영 뒤처지고, 느리면 후반이 무의미해진다.
//
// 100 을 나눈 정수로 적는다. 실수로 두면 기기마다 반올림이 달라져 같은
// 스테이지의 몬스터 체력이 서로 달라진다.
#define WAVE_HP_TIER_MUL		117

// 계단을 무한정 올리면 long long 도 넘친다. 이 값이면 60,000 스테이지라
// 어떤 콘텐츠보다 멀다.
#define WAVE_HP_MAX_TIER		120

//---- 보스 체력 ----
//
// 보스 자리는 그 자리에 있던 잡몹 체력에 배수를 곱한다. wave[] 세번째 칸이
// 자리를 들고 있다(Def.h의 MONSTERTYPE_*).
//
// 왜 곱셈인가. 잡몹 체력은 이미 무기 곡선을 따라 오르고 있으므로(위 참조),
// 보스에 고정값을 주면 어느 구간에서는 벽이고 어느 구간에서는 허수아비가
// 된다. 배수로 두면 어느 구간에서든 "잡몹 몇 마리분"이라는 감각이 같다.
//
// 하트 경제와 짝이다. 잡몹 하나에 하트 한 뭉치를 쓰고 상자가 그걸 도로
// 채워주므로, 대보스 100배는 "쌓아둔 하트를 여기서 다 쓴다"는 뜻이 된다.
#define WAVE_HP_SUBBOSS_MUL		5		//소보스 : 잡몹의 5배
#define WAVE_HP_MIDBOSS_MUL		10		//중보스 : 잡몹의 10배
#define WAVE_HP_BIGBOSS_MUL		100		//대보스 : 잡몹의 100배

//---- 하트 ----
//
// 하트는 공격 횟수다(ONEHEARTONEATTACK). 잡몹을 잡으면 상자가 하트를
// 도로 채워주는데, 딱 맞게 채우면 제자리걸음이라 조금 넘치게 준다.
// 그 넘친 몫이 쌓여서 대보스 앞에서 한 번에 쓰인다.
//
// 상자가 "얼마를 주는가"가 아니라 "어디까지 채우는가"로 적는다. 맥스치
// (GetInitHeart())가 레벨을 따라 오르므로, 고정 수량으로 두면 후반에
// 상자가 무의미해진다.
//---- 하트 상한과 회복 ----
//
// 레벨 하나에 상한 +10, 시간당 회복 +1 이다.
//
// 열 레벨마다 한 계단씩 밟았었다. 레벨이 오르는 길이 아예 없던 동안에는
// 어느 쪽이든 같았지만, 이제 적을 잡으면 오른다. 계단이면 아홉 번은
// 올려도 아무 일이 없고 열 번째만 뛴다 - 올린 보람이 열 번에 한 번만
// 오는 셈이다.
//
// 상한과 회복을 같은 결로 둔다. 상한만 레벨마다 늘고 회복은 열 레벨마다
// 늘면, 레벨이 오를수록 가득 채우는 데 걸리는 시간이 길어진다.
//
//     레벨  1   상한  60   회복 11/시간   가득까지 5.5 시간
//     레벨 20   상한 250   회복 30/시간   가득까지 8.3 시간
//     레벨 99   상한 1040  회복 109/시간  가득까지 9.5 시간
#define HEART_MAX_BASE			50
#define HEART_MAX_PER_LEVEL		10
#define HEART_REGEN_BASE		10
#define HEART_REGEN_PER_LEVEL	1

#define HEART_REFILL_PCT		110		//잡몹 상자 : 맥스의 110%까지
#define HEART_REFILL_BOSS_PCT	200		//보스 상자 : 맥스의 200%까지

//---- 히어로 체력 ----
//
// 체력 = 기본 + 유저레벨 x 계수 + (허리 + 신발) x 계수
//
// 만렙 기준으로 장비가 일곱, 기본과 레벨이 셋이 되게 잡았다.
//
//     초반 (lv 5,  허리+신발 10)    60 + 150 + 70    = 280    장비 25%
//     중반 (lv 50, 합 120)          60 + 1,500 + 840 = 2,400  장비 35%
//     만렙 (lv 99, 합 1,000)        60 + 2,970 + 7,000 = 10,030  장비 70%
//
// 초반에는 레벨이 바닥을 깔고 뒤로 갈수록 장비가 가져간다. 레벨은 99 에서
// 멈추고 장비는 계속 오르므로 저절로 그렇게 된다.
#define HERO_BASE_HP			60
#define HERO_HP_PER_LEVEL		30
#define HERO_HP_PER_ARMOR		700	//(허리+신발) x 7.0

//---- 경험치 ----
//
// 적을 잡으면 그 몫만큼 유저 레벨이 오른다. 지금까지는 오르는 길이 아예
// 없었다 - LevelUp() 을 부르는 곳이 디버그 키 하나였고 적의 add_exp 는
// 360 마리가 전부 0 이었다.
//
// 값을 표에 적지 않고 체력에서 나눈다. 체력 곡선이 이미 등비로 오르므로
// (WAVE_HP_TIER_MUL) 경험치도 같이 오른다. 표에 적으면 곡선을 고칠 때마다
// 표도 같이 고쳐야 하고, 잊으면 조용히 어긋난다.
//
// 30 으로 나눈 것은 양 끝을 맞춘 값이다. 1 스테이지 잡몹(264)이 9 를 주고
// 소보스가 45 를 주니 첫 보스에서 두어 레벨이 오른다. 97 레벨 구간은
// lvUpExp 가 20 만이고 그 구간 잡몹이 2 천쯤을 주므로 백 마리다.
#define ENEMY_EXP_DIV			30
//
// 보스 배수를 따로 두지 않는다. 보스는 maxhp 자체가 이미 배수만큼
// 크므로(GetWaveHpMul) 여기서 나누면 경험치도 저절로 그 배수다.
// 아무 일도 안 하는 손잡이를 두면 나중에 그것을 돌려보고 안 듣는다고
// 한참 헤맨다.

//---- 장비 강화 ----
//
// itemPow 에서 무기 한 자루가 차지하는 칸 수. itemLevelLimit 표가 그리던
// 규칙(0, 5, 10, ... 35)을 표 밖에서도 잇는다.
#define ITEMPOW_PER_TIER		5

// 강화 배율. 기본 수치에 곱한다. 칸 하나가 한 레벨이고 0 이 강화 안 한
// 것이다. 만렙은 GetEquipMaxLevel() = 14 다.
//
// [왜 바꾸는가]
// 전에는 두 곳이 서로 다르게 굴었다.
//
//     무기    itemPow[base + lv]        한 레벨에 +1 (등차)
//     방어구  value * (100 + lv * 10)   한 레벨에 +10% (등비)
//
// 무기 쪽이 특히 문제였다. 첫 검이 10 이고 다음 자루가 15 인데 강화는 한
// 레벨에 1 이다. 다섯 레벨을 올려도 +4 라, 다음 자루를 줍는 편이 언제나
// 낫다. 강화를 할 이유가 없었다.
//
// [왜 매 레벨 같은 비율인가]
// 클래시로얄을 따랐다. 거기는 카드 한 레벨이 언제나 +10% 다. 앞이 크거나
// 뒤가 큰 곡선을 두지 않는다.
//
// 그렇게 두면 "한 레벨의 값어치" 가 어디서나 같아서, 지금 올릴지 나중에
// 올릴지를 값만 보고 정할 수 있다. 곡선에 기울기를 주면 그 판단이 곡선의
// 어느 자리에 있느냐에 따라 달라지고, 그것을 사용자가 알 길이 없다.
//
// 속도는 곡선이 아니라 비용이 잡는다. 클래시로얄도 그렇다 - 배율은 늘
// +10% 이고 필요한 카드 수가 가파르게 오른다. 우리 비용표도 이미 그렇게
// 생겼다(upgradeCostEquip / upgradeCostCrew).
//
//     레벨 14 에서 3.8 배. 자루 사이가 1.5 배(10 -> 15)이므로, 한 자루
//     낮은 것을 키운 편이 갓 주운 윗자루보다 낫다.
#define EQUIP_LEVEL_MUL_LIST \
	100, 110, 121, 133, 146, 161, 177, 195, \
	214, 236, 259, 285, 314, 345, 380

//---- 동료 강화 ----
//
// 장비와 같은 곡선을 쓴다. 클래시로얄이 카드 종류를 안 가리고 +10% 인
// 것과 같다.
//
// 앞을 가파르게 두는 안도 있었다 - 동료는 중복 카드를 태우고 카드는 뒤로
// 갈수록 모으기 어려우니 초반 한 장이 크게 느껴지게 하자는 것이었다.
// 그런데 그 어려움은 이미 비용표가 말하고 있다(upgradeCostCrew 는 조각이
// 1, 2, 4, 10, 20, 50, 100 으로 오른다). 곡선에서 또 말하면 두 번 말하는
// 것이고, 두 곳이 서로 어긋나면 어느 쪽이 뜻인지 알 수 없게 된다.
//
// 장비와 만렙이 같은 것도 이 방식의 덤이다.
#define CREW_LEVEL_MUL_LIST \
	100, 110, 121, 133, 146, 161, 177, 195, \
	214, 236, 259, 285, 314, 345, 380

//---- 밸런스 재기 ----
//
// 켜면 몬스터를 하나 잡을 때마다 한 줄 남긴다.
//
//     BAL: w=4 소보스 hp=1650 맞은수=110 한대=15 하트=110 남은하트=-60
//
// 밸런스는 "몇 대에 잡히는가" 에서 시작한다. 그 값이 하트 소모를 정하고,
// 하트 소모가 보스 앞에서 얼마나 쌓이는지를 정한다. 그런데 그 값은 계산
