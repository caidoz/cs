//---- 몬스터 체력 ----
//
// [왜 등비인가]
// 전에는 등차였다.
//
//     100 * (waveIdx + 10) * (100 + ADDHP) / 10
//
// 1스테이지 10,000 에서 1000스테이지 1,009,000 까지 x100.9 로 곧게 올라갔다.
// 그런데 주인공의 힘은 무기가 정하고 무기는 등비다(x1.145 / 자루). 모양이
// 다른 두 곡선은 어디선가 반드시 엇갈린다. 초반은 벽이고 후반은 시시해진다.
//
// [기준점]
// 튜토리얼이 답을 들고 있었다.
//
//     TUTORIAL_WAVE_HP_3RD  체력 100  "하트 3배 베팅 공격에만 죽도록"
//     TUTORIAL_WAVE_HP_BOSS 체력 300  "동료 3중첩 강공격 한 방에"
//
// betHeart[2] 가 3 이므로 그때 주인공의 한 대는 33 안팎이라는 뜻이다.
// 첫 검이 10 이니 실제로 때리는 값은 무기값의 3배쯤 된다(스탯과 동료).
//
// 그래서 첫 몬스터를 "보통 공격 열 대"로 잡는다. 33 * 10 = 330. 튜토리얼
// 보스(300)와 비슷한 자리다. 지금 값 10,000 은 여기서 30배가 넘었다.
