//---- 진행 속도 ----
//
// 무기 한 자루를 얻는 데 걸리는 스테이지 수. 몬스터 체력 곡선이 이 값을
// 기준으로 한 계단씩 오른다. 무기 표(itemValue) 와 짝이므로 한쪽만 바꾸면
// 안 된다.
#define WAVE_STAGE_PER_TIER		500

//---- 몬스터 체력 ----
//
// [왜 등비인가]
// 전에는 등차였다.
//
//     100 * (waveIdx + 10) * (100 + ADDHP) / 10
//
// 1스테이지 10,000 에서 1000스테이지 1,009,000 까지 x100.9 로 곧게 올라갔다.
// 그런데 주인공의 힘은 무기가 정하고 무기는 등비다(x1.145 / 자루). 모양이
// 다른 두 곡선은 어디선가 반드시 엇갈린다. 초반은 벽이고 후반은 시시해진다.
//
// [기준점]
// 튜토리얼이 답을 들고 있었다.
//
//     TUTORIAL_WAVEIDX_3RD  체력 100  "하트 3배 베팅 공격에만 죽도록"
//     TUTORIAL_BOSS_HP      300       "동료 3중첩 강공격 한 방에"
//
// betHeart[2] 가 3 이므로 그때 주인공의 한 대는 33 안팎이라는 뜻이다.
// 첫 검이 10 이니 실제로 때리는 값은 무기값의 3배쯤 된다(스탯과 동료).
//
// 그래서 첫 몬스터를 "보통 공격 열 대"로 잡는다. 33 * 10 = 330. 튜토리얼
// 보스(300)와 비슷한 자리다. 지금 값 10,000 은 여기서 30배가 넘었다.
#define WAVE_HP_BASE			330

// [계단 크기]
// 무기 한 자루(500스테이지)마다 체력이 몇 배가 되는가.
//
// 주인공이 35자루를 다 모으는 동안 얻는 배수를 어림하면
//
//     무기      x100   (10 -> 999)
//     장갑      x1.8   (공격력 +80%)
//     강화      x1.5
//     ------------------
//     합계      x270
//
// 이걸 35계단에 나누면 270^(1/35) = 1.174 다. 즉 체력이 이 속도보다 빠르면
// 아무리 좋은 장비를 껴도 영영 뒤처지고, 느리면 후반이 무의미해진다.
//
// 100 을 나눈 정수로 적는다. 실수로 두면 기기마다 반올림이 달라져 같은
// 스테이지의 몬스터 체력이 서로 달라진다.
#define WAVE_HP_TIER_MUL		117

// 계단을 무한정 올리면 long long 도 넘친다. 이 값이면 60,000 스테이지라
// 어떤 콘텐츠보다 멀다.
#define WAVE_HP_MAX_TIER		120

//---- 시험용 ----
//
// 몬스터가 한 대에 죽으면 룰렛과 스킬 연출을 끝까지 볼 수 없다. 곡선은
// 그대로 두고 전체에 곱하기만 한다.
//
// 시연이 끝나면 1 로 되돌린다.
#define WAVE_HP_TEST_MUL		300

#endif
