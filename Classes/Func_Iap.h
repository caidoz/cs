#pragma once
#include "Core.h"
#include "Config/IapConfig.h"

#ifndef _FUNC_IAP_H_
#define _FUNC_IAP_H_

//=============================================================================
// 결제 계층
//
// 여기서 지키는 것은 하나다 — 돈이 나갔으면 반드시 받는다.
//
// 그것이 어려운 이유는, 돈이 나가는 곳(스토어)과 물건을 주는 곳(우리 서버)이
// 다르고 그 사이에 네트워크와 앱 종료가 끼기 때문이다. 흐름을 펴 보면 값을
// 치른 뒤에 끊길 수 있는 자리가 셋이다.
//
//     1. 스토어에 결제를 요청한다
//        ├─ 여기서 앱이 죽으면? 스토어가 결제를 끝냈을 수도 있다.
//     2. 스토어가 "됐다"고 답한다 (돈은 이 시점에 나갔다)
//        ├─ 여기서 앱이 죽으면? 돈은 나갔는데 서버는 모른다.
//     3. 영수증을 서버에 보낸다
//        ├─ 여기서 답을 못 받으면? 지급됐는지 안 됐는지 알 수 없다.
//     4. 서버가 지급한다
//
// 그래서 "안 끊기게 한다"가 아니라 "끊겨도 이어서 한다"로 만든다. 방법은
// 종이 한 장이다 — 대기 장부.
//
//     스토어를 부르기 전에 장부에 적는다.
//     서버가 지급했다고 답해야 지운다.
//     부팅할 때마다 장부에 남은 것을 다시 보낸다.
//
// 장부가 비어 있지 않다는 것은 "돈은 나갔을 수 있는데 아직 못 받았다"는
// 뜻이다. 그 상태로는 조용히 넘어가지 않는다.
//
// -----------------------------------------------------------------------------
// 클라이언트는 지급량을 모른다
// -----------------------------------------------------------------------------
//
// 무엇을 얼마나 주는지는 서버의 product 표에 있다. 클라이언트가 보내는 것은
// 상품 ID 와 영수증뿐이다. 지급량을 클라이언트가 보내면, 그 값을 고친 빌드가
// "천만 개짜리를 샀다"고 말하는 것을 막을 수 없다.
//
// 지급 결과도 클라이언트가 더하지 않는다. 서버가 더한 뒤 판 전체를 돌려주고
// 클라이언트는 그것으로 덮는다. 더하는 자리가 하나뿐이면 두 번 더할 일이 없다.
//=============================================================================

//대기 한 건의 상태.
typedef enum _iapState {
	IAPSTATE_NONE = 0,
	IAPSTATE_ASKING,	//스토어에 물어보는 중. 돈이 나갔는지 아직 모른다.
	IAPSTATE_BOUGHT,	//스토어가 됐다고 했다. 돈은 나갔다. 서버에 보내야 한다.
	IAPSTATE_SENDING,	//서버에 보내는 중.
	TOTALIAPSTATE,
} IAPSTATEDEF;

//결제 한 건의 결과.
typedef enum _iapResult {
	IAPRESULT_NONE = 0,	//아직
	IAPRESULT_OK,		//지급됐다
	IAPRESULT_CANCEL,	//사용자가 취소했다. 돈은 안 나갔다.
	IAPRESULT_FAIL,		//스토어가 거절했다. 돈은 안 나갔다.
	IAPRESULT_REJECT,	//서버가 거절했다. 돈은 나갔을 수 있다 — 문의 대상이다.
	TOTALIAPRESULT,
} IAPRESULTDEF;

//---- 켜고 끄기 ----
void IapInit(void);		//부팅 때 한 번. 장부를 읽고 남은 것을 되살린다.
void IapUpdate(void);	//매 프레임 한 번.

//---- 사기 ----
//
//시작되면 true. 이미 다른 결제가 도는 중이거나 결제가 꺼져 있으면 false.
bool IapBuy(int product);

//지금 결제가 도는 중인가. 도는 동안에는 상점 버튼을 잠가야 한다.
bool IapIsBusy(void);

//---- 결과 보기 ----
//
//한 번 물으면 지워진다. 같은 것을 두 번 띄우지 않게.
int IapTakeResult(void);

//그 결과가 어떤 상품이었는지. IapTakeResult() 와 같이 쓴다.
int IapLastProduct(void);

//---- 대기 ----
//
//아직 못 받은 결제가 몇 건인가. 0 이 아니면 "받는 중입니다" 를 띄워야 한다.
//사용자가 돈을 냈는데 화면에 아무 말이 없으면 그것이 제일 나쁘다.
int IapPendingCount(void);

//---- 패스 ----
//
// 30일권이다. 자동갱신 구독이 아니라, 사면 그만큼 기간이 밀리고 지나면 꺼진다.
// 남아 있을 때 또 사면 서버가 남은 기간 뒤에 이어 붙인다.
//
// 켜져 있는지는 게임 시각으로 본다. MC_knlCurrentTimeStamp() 는 서버와
// 맞춰진 시각이라(Func_Net.h 의 gNetTimeOffset), 기기 시계를 돌려도 안 늘어난다.
bool IapHeartPass(void);
bool IapGrowthPass(void);

//패스가 언제까지인지. 화면에 "n일 남음" 을 띄울 때 쓴다. 없으면 0.
long IapPassUntil(bool growth);

//상품의 스토어 ID. 로그와 서버에 보낼 때 쓴다.
const char* IapProductId(int product);

//화면에 띄울 이름.
//
//스토어가 답했으면 스토어가 준 이름이다. 아직이면 IapConfig.h 에 적어둔
//것을 쓴다. 나라마다 다른 말로 보여야 하므로 스토어 쪽이 정답이다.
const char* IapProductName(int product);

//화면에 띄울 값.
//
//스토어가 준 현지 통화 문자열이다("₩5,500", "$3.99"). 아직이면 빈 문자열이다.
//
//값을 클라이언트에 적어두면 안 된다. 스토어가 나라와 환율에 따라 정하고
//바꾼다. 적어둔 숫자를 띄우면 해외에서 틀린 값이 뜨고 심사에서도 걸린다.
const char* IapPriceText(int product);

#endif
