"""Bake artillery animation assets from existing CMF / projectile art.
No source art is repainted. Re-run after changing artillery.json or native art.
"""
import json, re, sys, math
from pathlib import Path
from PIL import Image, ImageOps, ImageDraw
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools/swords'))
from build_sword_poses import array
profiles=json.loads((ROOT/'content/castles/artillery.json').read_text(encoding='utf-8'))
blob=(ROOT/'Classes/Data/CmfBlob.cpp').read_text(encoding='utf-8-sig')
mi,cnt,off=[array(blob,n) for n in ('cmfMotionImgBlob','cmfMotionImgCntBlob','cmfOffBlob')]
ms,cs,os=[array(blob,n)[1] for n in ('cmfMotionImgSlot','cmfMotionImgCntSlot','cmfOffSlot')]
we=Image.open(ROOT/'Resources/res/we.png').convert('RGBA')
common=Image.open(ROOT/'Resources/res/cc.png').convert('RGBA')
crew=Image.open(ROOT/'Resources/res/crewBullet.png').convert('RGBA')
def motion(n):
    start,count=cnt[cs+n*2:cs+n*2+2]
    out=Image.new('RGBA',(1024,1024))
    for at in range(count):
        img,x,y,flags=mi[ms+(start+at)*4:ms+(start+at+1)*4]
        if 45<=img<96: raise ValueError(f'Non-projectile CMF part {img} in {n}')
        sx,sy,w,h=off[os+img*4:os+img*4+4]
        art=(common if img<45 else we).crop((sx,sy,sx+w,sy+h))
        if flags&1: art=ImageOps.mirror(art)
        angle=((flags&6)>>1)*90*(-1 if flags&1 else 1)
        art=art.rotate(-angle,expand=True,resample=Image.Resampling.NEAREST)
        scale=(flags>>6)+1
        if scale>1: art=art.resize((art.width*scale,art.height*scale),Image.Resampling.NEAREST)
        out.alpha_composite(art,(512+x,512+y))
    return out.crop(out.getbbox())
def source(spec):
    family,value=spec.split(':')
    if family=='crew':
        n=int(value); return crew.crop((n%16*64,n//16*64,n%16*64+64,n//16*64+64))
    if family=='diana': return motion(int(value))
    x,y,w,h=map(int,value.split(','))
    art=we.crop((x,y,x+w,y+h))
    # Tight effect-sheet crops can contain a detached tip from a neighbour.
    # Keep the largest connected silhouette without repainting its pixels.
    alpha=art.getchannel('A')
    points={(xx,yy) for yy in range(h) for xx in range(w) if alpha.getpixel((xx,yy))>0}
    largest=set()
    while points:
        seed=points.pop(); connected={seed}; pending=[seed]
        while pending:
            xx,yy=pending.pop()
            for dx in (-1,0,1):
                for dy in (-1,0,1):
                    q=(xx+dx,yy+dy)
                    if q in points: points.remove(q); connected.add(q); pending.append(q)
        if len(connected)>len(largest): largest=connected
    mask=Image.new('L',art.size)
    for q in largest: mask.putpixel(q,alpha.getpixel(q))
    art.putalpha(mask)
    return art
atlas=Image.new('RGBA',(8*96,31*96))
rects=[]
preview=Image.new('RGBA',(8*96,10*150),(24,30,40,255))
draw=ImageDraw.Draw(preview)
for group in range(30):
    grade=group%10; p=profiles[grade]; family=group//10
    for frame in range(8):
        if family==0:
            spec=p['asset']
            if spec=='diana:220': spec=f'diana:{220+frame%2}'
            if spec=='diana:233': spec=f'diana:{233+frame%2}'
            art=source(spec)
            if p['kind']=='Laser':
                art=art.rotate(45 if frame%2==0 else -45,expand=True,resample=Image.Resampling.NEAREST)
        elif family==1:
            art=motion(224+min(frame,7)) if p['kind'] in ('Rockets','Homing','Heavy') else source(p['asset'])
        else:
            art=source('we:132,376,64,64' if grade<6 else 'we:246,0,72,72')
        bbox=art.getbbox()
        if not bbox: raise ValueError(f'Empty frame {group}:{frame}')
        art=art.crop(bbox)
        pulse=(0.94+0.06*math.sin(frame/8*2*math.pi)) if family==0 else (0.35+0.65*math.sin((frame+1)/9*math.pi))
        factor=min(88/art.width,88/art.height)*pulse
        art=art.resize((max(1,round(art.width*factor)),max(1,round(art.height*factor))),Image.Resampling.NEAREST)
        if family: art.putalpha(art.getchannel('A').point(lambda a:round(a*(1-frame/10))))
        x,y=frame*96,group*96
        atlas.alpha_composite(art,(x,y))
        rects.append((x,y,art.width,art.height))
        if family==0:
            preview.alpha_composite(art,(x+(96-art.width)//2,grade*150+30+(96-art.height)//2))
    if family==0: draw.text((5,grade*150+5),f"Castle {grade+1}: {p['kind']} / {p['hits']} hits",fill='white')
for frame in range(8):
    art=source('crew:68').rotate(frame*45,expand=True,resample=Image.Resampling.NEAREST)
    art.thumbnail((88,88),Image.Resampling.NEAREST)
    atlas.alpha_composite(art,(frame*96,30*96))
    rects.append((frame*96,30*96,art.width,art.height))
dest=ROOT/'Resources/res/castle_artillery'; dest.mkdir(parents=True,exist_ok=True)
atlas.save(dest/'attacks.png')
preview.save(ROOT/'output/castle-artillery-preview.png')
header=['// Generated by tools/castles/build_artillery.py.','#pragma once',
        'struct CastleArtilleryFrame { int x,y,w,h; };','static const CastleArtilleryFrame kCastleArtilleryFrames[248] = {']
header+=['    {%d,%d,%d,%d},'%r for r in rects]; header+=['};']
(ROOT/'Classes/Data/CastleArtilleryFrames.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
defs=['// Generated from content/castles/artillery.json.','static const Profile kProfiles[10] = {']
for p in profiles:
    defs.append('    {"%s", %s, %d, %d, %d, %d, %d, 0x%s, %.1ff},' %
                (p['name'],p['kind'],p['cooldown'],p['hits'],p['interval'],p['flight'],p['damagePercent'],p['color'],p['size']))
defs+=['};']
(ROOT/'Classes/Data/CastleArtilleryProfiles.inc').write_text('\n'.join(defs)+'\n',encoding='utf-8')
(dest/'manifest.json').write_text(json.dumps({'source':'existing we.png, crewBullet.png and Diana CMF',
    'framesPerAnimation':8,'groups':['projectile','impact','muzzle','gatling rotor'],'profiles':profiles,'rects':rects},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('Baked 248 frames: 10 projectiles, 10 impacts, 10 muzzle animations, gatling rotor')
