"""Register complete authored cutaways; never change image pixels or castle geometry."""
from pathlib import Path
import json, re, hashlib
import numpy as np
from PIL import Image

root=Path(__file__).resolve().parents[2]
assets=root/'Resources/res/castle_room_integrated_v4'
source=(root/'Classes/Data/SoftCastleSectors.h').read_text(encoding='utf-8-sig').split('static const Sector Sectors[10][5]={',1)[1].split('\n};',1)[0]
sectors=[]
for line in source.splitlines():
    cells=re.findall(r'\{([^{}]+)\}',line)
    if cells:sectors.append([[float(v.strip().rstrip('f')) for v in cell.split(',')] for cell in cells])
assert len(sectors)==10
facility_source=(root/'Classes/Data/CastleFacilities.h').read_text(encoding='utf-8-sig')
mapping_text=facility_source.split('static const int SectorIndex[10][5]={',1)[1].split('};',1)[0]
mapping=[[int(v) for v in row.split(',')] for row in re.findall(r'\{([^{}]+)\}',mapping_text)]
assert len(mapping)==10
art_regions=[
 [[.08,.44,.84,.30]],
 [[.10,.41,.42,.36],[.53,.39,.21,.24]],
 [[.10,.65,.43,.19],[.32,.34,.32,.29]],
 [[.30,.49,.35,.35],[.10,.48,.20,.20],[.68,.68,.22,.16]],
 [[.10,.67,.57,.20],[.07,.47,.32,.18],[.36,.28,.33,.30]],
 [[.17,.72,.61,.16],[.16,.57,.25,.15],[.54,.56,.23,.16],[.29,.36,.41,.21]],
 [[.14,.74,.45,.14],[.60,.74,.27,.14],[.22,.56,.46,.20],[.26,.32,.42,.22]],
 [[.22,.67,.42,.20],[.63,.69,.23,.18],[.12,.43,.25,.19],[.37,.30,.38,.31],[.75,.43,.17,.19]],
 [[.18,.77,.58,.13],[.12,.57,.28,.20],[.66,.57,.20,.20],[.12,.37,.24,.18],[.41,.48,.25,.28]],
 [[.36,.78,.50,.10],[.09,.77,.27,.11],[.13,.41,.25,.14],[.71,.46,.21,.17],[.37,.30,.35,.40]]
]
sizes=[];all_frames=[];audit=[]
for c in range(10):
    path=assets/f'castle-{c+1:02}.png'
    paths=[assets/f'castle-10-level-{lv}.png' for lv in range(6)] if c==9 else [path]*6
    assert all(p.exists() for p in paths),(c,'missing complete upgrade states')
    bodies=[];state_sizes=[];cache={}
    for lv in range(6):
        state_path=paths[lv]
        if state_path not in cache:cache[state_path]=np.array(Image.open(state_path).convert('RGBA'))
        pixels=cache[state_path];height,width=pixels.shape[:2]
        state_sizes.append([width,height])
        assert np.any(pixels[:,:,3]==0),(state_path,'missing transparent background')
        col,row=lv%3,lv//3
        left,right=(0,width) if c==9 else (col*width//3,(col+1)*width//3)
        top,bottom=(0,height) if c==9 else (row*height//2,(row+1)*height//2)
        alpha=pixels[top:bottom,left:right,3]>200
        ys,xs=np.nonzero(alpha)
        assert len(xs)>100,(c,lv,'missing castle')
        # Real-alpha extents in each equal grid cell. No pixel resampling/editing.
        x=left+int(xs.min());y=top+int(ys.min())
        w=int(xs.max()-xs.min()+1);h=int(ys.max()-ys.min()+1)
        if c==8:
            # Its second row starts above the mathematical half-grid. Avoid
            # including the next castle's crystal tip in the first-row bounds.
            y=43 if lv<3 else 758
            h=626 if lv<3 else 633
        bodies.append([x,y,w,h])
    frames=[]
    for room,physical in enumerate(mapping[c]):
        x,y,w,h=art_regions[c][physical]
        for lv,(bx,by,bw,bh) in enumerate(bodies):
            width,height=state_sizes[lv]
            sx=bx+round(x*bw);sy=by+round(y*bh)
            sw=max(1,round(w*bw));sh=max(1,round(h*bh))
            assert 0<=sx<sx+sw<=width and 0<=sy<sy+sh<=height
            frames.append(dict(room=room,physical_room=physical,level=lv,crop=[sx,sy,sw,sh]))
    sizes.append(state_sizes);all_frames.append(bodies)
    audit.append(dict(castle=c+1,sizes=state_sizes,files=[p.name for p in paths],bodies=bodies,frames=frames,sha256=[hashlib.sha256(p.read_bytes()).hexdigest() for p in paths]))
lines=['#pragma once','// Generated by tools/castles/register_integrated_rooms.py. Image pixels unchanged.',
       'namespace CastleRoomIntegrated {','struct Crop {int x,y,w,h;};','static const int Sizes[10][6][2]={']
lines += [' {'+','.join('{'+','.join(map(str,size))+'}' for size in states)+'},' for states in sizes]
lines+=['};','static const Crop Bodies[10][6]={']
lines += [' {'+','.join('{'+','.join(map(str,b))+'}' for b in bodies)+'},' for bodies in all_frames]
lines+=['};','struct Region {float x,y,w,h;};','static const Region Regions[10][5]={']
lines += [' {'+','.join('{'+','.join(f'{v:.6f}f' for v in s[:4])+'}' for s in row)+'},' for row in sectors]
lines+=['};','// Art apertures include wall-mounted furnishings; NPC standing sectors stay unchanged.','static const Region ArtRegions[10][5]={']
lines += [' {'+','.join('{'+','.join(f'{v:.6f}f' for v in s)+'}' for s in row)+'},' for row in art_regions]
lines+=['};','}']
(root/'Classes/Data/CastleRoomIntegrated.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
(assets/'registration.json').write_text(json.dumps(audit,indent=2)+'\n',encoding='utf-8')
print(f'Registered {len(audit)}/10 integrated castle atlases, six complete cutaway states each')
