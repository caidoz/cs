"""Export the existing castle sectors as NPC standing-zone arrays for Claude."""
from pathlib import Path
import json, re, math

root=Path(__file__).resolve().parents[2]
text=(root/'Classes/Data/SoftCastleSectors.h').read_text(encoding='utf-8-sig')
body=text.split('static const Sector Sectors[10][5]={',1)[1].split('\n};',1)[0]
sector_rows=[]
for line in body.splitlines():
    cells=re.findall(r'\{([^{}]+)\}',line)
    if cells:sector_rows.append([[float(v.strip().rstrip('f')) for v in cell.split(',')] for cell in cells])
assert len(sector_rows)==10
facilities=(root/'Classes/Data/CastleFacilities.h').read_text(encoding='utf-8-sig')
names=re.findall(r'\{"([^"]+)","([^"]+)",(\d+)\}',facilities)
mapping_text=facilities.split('static const int SectorIndex[10][5]={',1)[1].split('};',1)[0]
mapping=[[int(v) for v in row.split(',')] for row in re.findall(r'\{([^{}]+)\}',mapping_text)]
rig_text=(root/'Classes/Data/IndividualCastleV4.h').read_text(encoding='utf-8-sig').split('static const Rig Rigs[10]={',1)[1].split('\n};',1)[0]
rigs=[]
for line in rig_text.splitlines():
    m=re.match(r'\s*\{([0-9]+),([0-9]+),([0-9]+),([0-9]+),',line)
    if m:rigs.append([int(v) for v in m.groups()])
assert len(rigs)==10
document={'version':1,'coordinates':'castle body normalized; origin top-left; x right; y down; NPC anchor is bottom-center of its visual bounds',
          'levels':[0,1,2,3,4,5],'gun_bounds':'exclude the live sdPlacement gun rectangle after screen conversion',
          'castles':[]}
header=['#pragma once','// Generated by tools/castles/export_npc_placement.py; see npc_placement.json.',
        'namespace CastleNpcPlacement {',
        'struct Area {float left,right,foot,depth,maxHeight,maxWidth;int recommended;};',
        'static const int Counts[10]={'+','.join(str(len(row)) for row in sector_rows)+'};',
        'static const Area Areas[10][5]={']
index=0
authored=json.loads((root/'Resources/res/castle_room_integrated_v4/npc_floors.json').read_text(encoding='utf-8'))['castles']
for c,sectors in enumerate(sector_rows):
    castle={'castle_index':c,'castle_level':c+1,'reference_body_size':{'width':rigs[c][2],'height':rigs[c][3]},'rooms':[]}
    entries=[]
    for room,(x,y,w,h,foot) in enumerate(sectors):
        facility=mapping[c].index(room)
        name,role,_=names[index+facility]
        left,right,foot,depth=authored[c][room]
        if c==8:foot*=.93/.91;depth*=.93/.91
        # The old sector is not a walkable floor. Clip to the authored floor,
        # leaving headroom for the shared screen-sized companions.
        x=max(0,left-.04);y=max(0,foot-.18);w=min(1,right+.04)-x;h=foot-y+.01
        max_height=foot-depth-y
        max_width=min((right-left)*.45,max_height*rigs[c][3]/rigs[c][2]*.70)
        x=max(0,left-max_width*.5);w=min(1,right+max_width*.5)-x
        count=max(1,min(6,math.floor((right-left)/max_width)-1))
        area={'left':round(left,6),'right':round(right,6),'foot':foot,'depth':round(depth,6),
              'max_height':round(max_height,6),'max_width':round(max_width,6),'recommended':count}
        anchors=[{'x':round(left+(right-left)*(i+1)/(count+1),6),'y':foot} for i in range(count)]
        castle['rooms'].append({'room_index':room,'facility_index':facility,'name':name,'role':role,
            'clip':{'left':x,'top':y,'width':w,'height':h},
            'feet_area':{'left':area['left'],'top':round(foot-depth,6),'width':round(right-left,6),'height':area['depth']},
            'area':area,'anchors':anchors})
        values=[area[key] for key in ('left','right','foot','depth','max_height','max_width')]
        entries.append('{'+','.join(f'{value:.6f}f' for value in values)+f',{count}'+'}')
        assert x<=left<right<=x+w and y<=foot-depth<=foot<=y+h+.00001
        assert max_height<=foot-depth-y+.00001
        assert left-max_width*.5>=x-.00001 and right+max_width*.5<=x+w+.00001
    document['castles'].append(castle)
    index+=len(sectors)
    header.append(' {'+','.join(entries)+'},')
header+=['};',
 'inline float SlotX(const Area& area,int slot,int count){',
 ' count=count<1?1:count;slot=slot<0?0:slot>=count?count-1:slot;',
 ' return area.left+(area.right-area.left)*(slot+1)/(count+1.0f);',
 '}',
 'inline bool ContainsFoot(const Area& area,float x,float y){return x>=area.left&&x<=area.right&&y>=area.foot-area.depth&&y<=area.foot;}',
 '}']
path=root/'Resources/res/castle_room_upgrades_v3/npc_placement.json'
path.write_text(json.dumps(document,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
(root/'Classes/Data/CastleNpcPlacement.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
print(f'PASS exported {len(sector_rows)} castles / {index} authored floor zones and safe anchors')
