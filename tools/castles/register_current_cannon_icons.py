"""Pack the current ten weapon cutouts into the existing 60-frame item atlas.

Generated source art stays untouched. Only uniform sprite fitting/registration
is performed here. Inventory footprints and enum/resource names stay stable.
"""
from pathlib import Path
import json
from PIL import Image

ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'content/castles/current_cannon_icons_v1'
OUT=ROOT/'Resources/res/inventory_cannon'
THEMES=['stone_catapult','flamethrower','rocket_battery','gatling','guided_missiles',
        'heavy_siege','ice_crystal','laser','tesla','gravity']
MUZZLES=[(.20,.10),(.96,.43),(.92,.28),(.98,.36),(.96,.18),
         (.94,.28),(.98,.20),(.98,.35),(.97,.30),(.97,.43)]

def build():
    OUT.mkdir(parents=True,exist_ok=True)
    atlas=Image.new('RGBA',(576,640))
    entries=[];frames=[]
    for castle in range(10):
        path=SOURCE/'originals'/f'cannon-{castle+1:02}.png'
        source=Image.open(path).convert('RGBA')
        assert source.getchannel('A').getextrema()[0]==0, path
        bounds=source.getchannel('A').point(lambda a:255 if a>=24 else 0).getbbox()
        assert bounds,path
        art=source.crop(bounds)
        for level in range(6):
            cols=2 if level<3 else 3;rows=2;width=cols*32;height=64
            scale=min((width-6)/art.width,(height-6)/art.height)
            fitted=art.resize((max(1,round(art.width*scale)),max(1,round(art.height*scale))),Image.Resampling.LANCZOS)
            icon=Image.new('RGBA',(width,height))
            icon.alpha_composite(fitted,((width-fitted.width)//2,(height-fitted.height)//2))
            bx,by,right,bottom=icon.getbbox();bw=right-bx;bh=bottom-by
            mx=bx+round((bw-1)*MUZZLES[castle][0]);my=by+round((bh-1)*MUZZLES[castle][1])
            filename=f'castle_{castle+1:02}_lv_{level}.png'
            icon.save(OUT/filename)
            sx=level*96+(96-width)//2;sy=castle*64;mask=0x33 if cols==2 else 0x77
            atlas.alpha_composite(icon,(sx,sy))
            frames.append('    {'+','.join(map(str,[sx,sy,width,height,cols,rows]))+f',0x{mask:X},'+','.join(map(str,[bx,by,bw,bh,mx,my]))+'},')
            entries.append(dict(castle=castle+1,level=level,grade=level,file=filename,theme=THEMES[castle],cols=cols,rows=rows,cells=mask,size=[width,height],atlasRect=[sx,sy,width,height],bodyRect=[bx,by,bw,bh],muzzle=[mx,my],sourceFile=str(path.relative_to(ROOT)),sourceRect=list(bounds),design='current base exterior shared by all grades'))
    atlas.save(OUT/'atlas.png')
    (OUT/'manifest.json').write_text(json.dumps(dict(tileSize=32,castles=10,levels=6,atlas='atlas.png',atlasSize=list(atlas.size),items=entries),indent=2),encoding='utf-8')
    header='''#pragma once
// Generated by tools/castles/register_current_cannon_icons.py.
namespace InventoryCannons {
enum { Castles=10, Levels=6, Count=60, TileSize=32 };
struct Frame { int x,y,w,h,cols,rows; unsigned int cells; int bx,by,bw,bh,muzzleX,muzzleY; };
static const Frame frames[Count]={
'''+ '\n'.join(frames)+'''
};
inline const Frame& Get(int castle,int level) {
    castle=castle<0?0:castle>=Castles?Castles-1:castle;
    level=level<0?0:level>=Levels?Levels-1:level;
    return frames[castle*Levels+level];
}
}
'''
    (ROOT/'Classes/Data/InventoryCannonSprites.h').write_text(header,encoding='utf-8')
    for e in entries:
        icon=Image.open(OUT/e['file']).convert('RGBA')
        x,y,w,h=e['atlasRect']
        assert icon.tobytes()==atlas.crop((x,y,x+w,y+h)).tobytes()
        bx,by,bw,bh=e['bodyRect']
        assert bw>0 and bh>0 and bx>=0 and by>=0 and bx+bw<=w and by+bh<=h
        assert e['cells'].bit_count()==e['cols']*e['rows']
    print('PASS 10 current weapon designs, 60 frame bounds, alpha, footprints and exact atlas copies')

if __name__=='__main__': build()
