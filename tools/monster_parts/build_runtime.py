"""Build runtime CMF part art and behaviour tables from reviewed selections.

Edit content/monster_parts/behaviors.json to change roles or active weapons.
Requires build_all.py and build_review.py outputs for the original source pixels.
"""
import json
from pathlib import Path
from PIL import Image
from build_all import ROOT, OUT

BEHAVIORS=ROOT/'content/monster_parts/behaviors.json'
def main():
    rows=json.loads((OUT/'catalogue.json').read_text(encoding='utf-8'))
    profiles=json.loads(BEHAVIORS.read_text(encoding='utf-8'))['profiles'];bybase={p['base_cmf']:i for i,p in enumerate(profiles)}
    assert len(profiles)==51
    roles={'core':'Core','attack':'Attack','support':'Support','guard':'Guard','recovery':'Recovery'}
    kinds={'strike':'Strike','rush':'Rush'}
    artout=ROOT/'Resources/res/monster_parts';artout.mkdir(parents=True,exist_ok=True)
    cell=64;side=2048;perpage=(side//cell)**2
    pages=[Image.new('RGBA',(side,side)) for _ in range((sum(len(r['icons']) for r in rows)+perpage-1)//perpage)]
    lines=['// Generated by tools/monster_parts/build_runtime.py. Edit behaviors.json and source selections.',
           '#pragma once','namespace MonsterParts {',
           'enum Role {Core,Attack,Support,Guard,Recovery,RoleCount};',
           'enum ActionKind {Strike,Rush};',
           'struct PartDef {const char* name;Role role;int width,height;};',
           'struct ActionDef {const char* name;ActionKind kind;int nativePattern,powerPct,hits;};',
           'struct SpeciesDef {int cmf,first,count,weaponCount;ActionDef actions[3];};',
           'struct ArtDef {int page,x,y,w,h;};',
           'struct EnemyDef {int species,firstArt,cmf;};',
           'static const PartDef Parts[]={']
    first=0;starts=[]
    for p in profiles:
        assert 1<=len(p['actions'])<=3 and 2<=len(p['parts'])<=5
        assert len(p['actions'])==sum(d['role']=='attack' for d in p['parts'])
        assert sum(d['role']=='core' for d in p['parts'])==1
        assert p['parts'][0]['role']=='core'
        assert any(d['role'] in ('attack','support') for d in p['parts'])
        for ai,a in enumerate(p['actions']):
            assert a['kind']!='heal' and a['hits']==1
            assert sum(d['role']=='attack' for d in p['parts'])>ai
        starts.append(first)
        for part in p['parts']:
            assert part['role'] in roles and 1<=part['width']<=2 and 1<=part['height']<=2
            lines.append(' {u8%s,%s,%d,%d},'%(json.dumps(part['name'],ensure_ascii=False),roles[part['role']],part['width'],part['height']));first+=1
    lines+=['};','static const SpeciesDef Species[]={']
    for pi,p in enumerate(profiles):
        actionrows=[]
        for ai,a in enumerate(p['actions']):
            assert a['kind'] in kinds and 0<=a['native_pattern']<=2 and 1<=a['hits']<=2 and 1<=a['power_pct']<=200
            actionrows.append('{u8%s,%s,%d,%d,%d}'%(json.dumps(a['name'],ensure_ascii=False),kinds[a['kind']],a['native_pattern'],a['power_pct'],a['hits']))
        while len(actionrows)<3:actionrows.append('{u8"",Strike,0,0,0}')
        lines.append(' {%d,%d,%d,%d,{%s}},'%(p['base_cmf'],starts[pi],len(p['parts']),len(p['actions']),','.join(actionrows)))
    lines+=['};','static const ArtDef Art[]={'];index=0;enemyrows=[]
    for r in rows:
        profile=profiles[bybase[r['base']]]
        assert len(r['icons'])==len(profile['parts'])
        enemyrows.append(' {%d,%d,%d},'%(bybase[r['base']],index,r['cmf']))
        for icon in r['icons']:
            im=Image.open(OUT/icon['asset']).convert('RGBA')
            scale=min(1,60/im.width,60/im.height)
            if scale<1:im=im.resize((max(1,int(im.width*scale)),max(1,int(im.height*scale))),Image.Resampling.NEAREST)
            page=index//perpage;x=(index%32)*cell+2;y=((index%perpage)//32)*cell+2
            pages[page].alpha_composite(im,(x,y))
            lines.append(' {%d,%d,%d,%d,%d},'%(page,x,y,im.width,im.height));index+=1
    lines+=['};','static const EnemyDef Enemies[]={']+enemyrows+['};',f'enum {{SpeciesCount=51,EnemyCount=357,AtlasCount={len(pages)}}};','}']
    target=ROOT/'Classes/Data/MonsterPartsData.h';target.write_text('\n'.join(lines)+'\n',encoding='utf-8-sig')
    for i,page in enumerate(pages):page.save(artout/f'atlas-{i}.png')
    (artout/'manifest.json').write_text(json.dumps(dict(icons=index,atlases=len(pages),filter='nearest',source='CMF PNG + reviewed crop/mask',behaviors='content/monster_parts/behaviors.json'),indent=2),encoding='utf-8')
    doc=ROOT/'docs/MONSTER_PARTS_COMBAT_DESIGN.md'
    marker='<!-- GENERATED_SPECIES_TABLE -->'
    if doc.exists():
        body=doc.read_text(encoding='utf-8').split(marker)[0]
        role_names={'core':'핵','attack':'공격','support':'보조','guard':'방어','recovery':'회복'}
        table=['| 몬스터 | CMF | 부위와 역할 | 한 턴의 공격 순서 |','| --- | --- | --- | --- |']
        for p in profiles:
            parts=' · '.join(f"{d['name']}({role_names[d['role']]})" for d in p['parts'])
            actions=' → '.join(a['name'] for a in p['actions'])
            table.append(f"| {p['name']} | {p['base_cmf']} | {parts} | {actions} |")
        doc.write_text(body+marker+'\n\n'+'\n'.join(table)+'\n',encoding='utf-8')
    print(f'Built {len(profiles)} profiles, {len(rows)} monsters, {index} icons, {len(pages)} atlases')

if __name__=='__main__':main()
