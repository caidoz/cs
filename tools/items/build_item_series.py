"""Split repainted sheets into registered 256px itemN assets without changing legacy atlases."""
from pathlib import Path
import argparse
import hashlib
import json
import shutil
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
WORK = ROOT / 'output/item-series'
DEST = ROOT / 'asset_library/reference/Resources/res/items'


def original(entry):
    x, y, w, h = entry['rect']
    with Image.open(ROOT / entry['source']) as image:
        return image.convert('RGBA').crop((x, y, x + w, y + h))


def build():
    catalog = json.loads((WORK / 'catalog.json').read_text(encoding='utf-8'))
    generation = json.loads((WORK / 'generation.json').read_text(encoding='utf-8'))
    sheets = {}
    boundaries = {}
    cell_rects = {}
    for record in generation['sheets']:
        name = record['name']
        saved = WORK / f'generated/{name}.png'
        source = Path(record['path'])
        if not source.is_absolute():
            source = ROOT / source
        if source.resolve() != saved.resolve():
            shutil.copyfile(source, saved)
        image = Image.open(saved).convert('RGBA')
        if image.getchannel('A').getextrema()[0] != 0:
            raise ValueError(f'{name}: sheet has no transparency')
        sheets[name] = image
        boundaries[name] = record.get('row_boundaries')
        cell_rects[name] = record.get('cell_rects')

    DEST.mkdir(parents=True, exist_ok=True)
    for entry in catalog['entries']:
        src = original(entry)
        target = Image.new('RGBA', (256, 256))
        if entry['active'] and not entry.get('reserved'):
            sheet = sheets[entry['sheet']]
            rows = 10 if entry['sheet'] == 'weapons' else 3 if entry['sheet'] == 'gloves' else 8
            col, row = entry['cell'] % 8, entry['cell'] // 8
            rect = (round(col * sheet.width / 8), round(row * sheet.height / rows),
                    round((col + 1) * sheet.width / 8), round((row + 1) * sheet.height / rows))
            if boundaries[entry['sheet']]:
                stops = boundaries[entry['sheet']]
                rect = (rect[0], stops[row], rect[2], stops[row + 1])
            if cell_rects[entry['sheet']]:
                rect = tuple(cell_rects[entry['sheet']][entry['cell']])
            tile = sheet.crop(rect)
            bbox = tile.getchannel('A').point(lambda a: 255 if a > 24 else 0).getbbox()
            if not bbox:
                raise ValueError(f'item{entry["id"]}: generated cell is empty')
            # Preserve the original occupied area and centre; do not stretch anatomy.
            tile = tile.crop(bbox)
            sx, sy, ex, ey = src.getchannel('A').getbbox()
            wanted = ((ex - sx) * 256 / src.width, (ey - sy) * 256 / src.height)
            scale = min(wanted[0] / tile.width, wanted[1] / tile.height)
            size = (max(1, round(tile.width * scale)), max(1, round(tile.height * scale)))
            tile = tile.resize(size, Image.Resampling.LANCZOS)
            x = round((sx + ex) * 128 / src.width - tile.width / 2)
            y = round((sy + ey) * 128 / src.height - tile.height / 2)
            target.alpha_composite(tile, (x, y))
            entry['rendered_from'] = f'generated/{entry["sheet"]}.png'
        elif entry.get('reserved'):
            # These are fragments of i7's large spinning coin animation, not icons.
            target = src.resize((256, 256), Image.Resampling.NEAREST)
            entry['rendered_from'] = 'reserved animation cell; renderer uses original atlas'

        # Use the already inspected faithful single-item samples where available.
        samples = {217: 'sword', 264: 'armor', 336: 'boots'}
        if entry['id'] in samples:
            sample = ROOT / f'output/equipment-style-sample-v2/{samples[entry["id"]]}-sample.png'
            if sample.exists():
                with Image.open(sample) as image:
                    target = image.convert('RGBA').resize((256, 256), Image.Resampling.LANCZOS)
                entry['rendered_from'] = sample.relative_to(ROOT).as_posix()
        target.save(DEST / f'item{entry["id"]}.png')
        entry['bounds'] = list(target.getchannel('A').point(lambda a: 255 if a > 24 else 0).getbbox() or (0, 0, 0, 0))
        entry['file'] = f'res/items/item{entry["id"]}.png'

    catalog['source_hashes'] = {
        name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
        for name in sorted({entry['source'] for entry in catalog['entries']})
    }
    (DEST / 'manifest.json').write_text(json.dumps(catalog, indent=2), encoding='utf-8')
    rows = []
    for entry in catalog['entries']:
        x, y, right, bottom = entry['bounds']
        active = entry['active'] and not entry.get('reserved')
        rows.append(f'{{{x},{y},{right-x},{bottom-y},{str(active).lower()}}}')
    (ROOT / 'Classes/ItemSeriesArt.h').write_text(
        '#pragma once\n// Generated by tools/items/build_item_series.py.\n'
        'namespace ItemSeries {\nstruct Art {int x,y,w,h;bool active;};\n'
        'static const Art Artwork[Count]={\n' + ',\n'.join(rows) + '\n};\n}\n', encoding='utf-8')
    gallery(catalog)
    verify()


def gallery(catalog):
    blocks = []
    for entry in catalog['entries']:
        if not entry['active'] or entry.get('reserved'):
            continue
        name = f'item{entry["id"]}'
        src_path = WORK / f'source/{name}.png'
        original(entry).save(src_path)
        blocks.append(f'<figure><figcaption>{name}</figcaption>'
                      f'<img class="old" src="source/{name}.png" title="Original">'
                      f'<img src="../../Resources/{entry["file"]}" title="256px repaint"></figure>')
    (WORK / 'index.html').write_text(
        '<!doctype html><meta charset="utf-8"><title>Item series: original / 256px</title>'
        '<style>body{background:#1c282c;color:#eee;font:16px system-ui}main{display:flex;flex-wrap:wrap}'
        'figure{margin:6px;padding:8px;background:#304044}img{width:96px;height:96px;object-fit:contain}'
        '.old{image-rendering:pixelated}figcaption{text-align:center}</style>'
        '<h1>Original / 256px material repaint</h1><main>' + ''.join(blocks) + '</main>', encoding='utf-8')


def verify():
    manifest = json.loads((DEST / 'manifest.json').read_text(encoding='utf-8'))
    assert len(manifest['entries']) == 608
    assert len(list(DEST.glob('item[0-9]*.png'))) == 608
    active = 0
    for entry in manifest['entries']:
        with Image.open(DEST / f'item{entry["id"]}.png') as image:
            assert image.size == (256, 256) and image.mode == 'RGBA', entry['id']
            if entry['active'] and not entry.get('reserved'):
                assert image.getchannel('A').getbbox(), entry['id']
                assert image.getchannel('A').getextrema()[0] == 0, entry['id']
                active += 1
            image.load()
    for path, digest in manifest['source_hashes'].items():
        assert hashlib.sha256((ROOT / path).read_bytes()).hexdigest() == digest, path
    print(f'PASS 608 RGBA files at 256x256; {active} active icons; legacy source hashes unchanged')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('action', choices=['build', 'verify'])
    options = parser.parse_args()
    build() if options.action == 'build' else verify()
