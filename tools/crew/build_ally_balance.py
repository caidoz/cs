"""Validate the authored balance table and generate runtime data + readable reports."""
import csv
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
ACTIONS=['Shield','Heal','Repair','Volley','Supply','Expose','Inspire','Cleanse','Strike','Bleed','Chill','Burn','Poison','Leech','Fortify','Shock','Discharge','PrototypeSmith','PrototypeCleric','PrototypeCaptain']
CONDITIONS=['Always','LowHp','HighHp','LowShield','EnemyLowHp','EnemyHighHp','EnemyDebuffed','EnemyClean','Front','Back','AdjacentWeapon','AdjacentCrew','EveryThird','Alone']
STATUS={'Burn':(5,4),'Poison':(6,8),'Chill':(3,3),'Shock':(4,5),'Bleed':(4,6),'Expose':(1,5)}

def effect(action,power):
    labels={'Shield':f'보호막 {power}%','Heal':f'체력 회복 {power}%',
            'Repair':f'성 수리 {power}%','Volley':f'일반탄 추가 사격 {power}%',
            'Supply':f'무기 준비 +{power}%','Expose':f'취약 {power}중첩',
            'Inspire':f'다음 적중탄 +{power}%p','Cleanse':'해로운 효과 1개 해제',
            'Strike':f'영웅 강타 {power}%','Bleed':f'출혈 {power}중첩',
            'Chill':f'냉기 {power}중첩','Burn':f'화상 {power}중첩',
            'Poison':f'중독 {power}중첩','Leech':f'흡수 회복 {power}%',
            'Fortify':f'다음 기본 공격 피해 -{power}%','Shock':f'감전 {power}중첩',
            'Discharge':f'감전 소비 방전 {power}%',
            'PrototypeSmith':f'성 수리 {power}% + 영웅 연계',
            'PrototypeCleric':f'조건부 체력 회복 {power}%',
            'PrototypeCaptain':f'엄호 사격 {power}%'}
    return labels[action]

def quoted(value):
    return json.dumps(value,ensure_ascii=False)

def main():
    catalog=json.loads((ROOT/'reports/hero_allies_64/catalog.json').read_text(encoding='utf-8'))
    with (ROOT/'content/hero_allies_balance.tsv').open(encoding='utf-8') as source:
        rows=list(csv.DictReader(source,delimiter='\t'))
    assert len(rows)==64
    authored=[]
    for index,row in enumerate(rows):
        assert int(row['id'])==index
        assert row['action'] in ACTIONS and row['condition'] in CONDITIONS
        for field in ['cols','rows','power','attack_percent']: row[field]=int(row[field])
        for field in ['attack_seconds','ability_seconds']: row[field]=float(row[field])
        assert row['cols'] in (1,2) and row['rows'] in (1,2)
        assert 2.4<=row['attack_seconds']<=5.2 and 3<=row['ability_seconds']<=16
        assert 75<=row['attack_percent']<=130
        row['id']=index;row['name']=catalog[index]['name'];row['npc_id']=catalog[index]['npc_id']
        row['npc_enum']=catalog[index]['npc_enum'];row['sprite']=catalog[index]['sprite']
        row['legacy_skills']=[catalog[index][f'skill{k}_id'] for k in range(1,4)]
        row['status']=({'name':row['action'],'cap':STATUS[row['action']][0],
                        'duration_seconds':STATUS[row['action']][1]} if row['action'] in STATUS else None)
        for hero in ['robin','diana','max']:
            action,power,seconds=row[hero].split(':')
            assert action in ACTIONS and 3<=float(seconds)<=16
            row[hero]={'action':action,'power':int(power),'cooldown_seconds':float(seconds)}
        authored.append(row)
    assert len({r['ability'] for r in authored})==64
    header=['// Generated by tools/crew/build_ally_balance.py from content/hero_allies_balance.tsv.',
            '#pragma once','namespace AllyBalance {',
            'enum class Action { '+', '.join(ACTIONS)+' };',
            'enum class Condition { '+', '.join(CONDITIONS)+' };',
            'struct Synergy { Action action; int power, cooldownMs; };',
            'struct Profile { int id,npc,cols,rows,attackMs,attackPercent; Action action; int abilityMs,power; Condition condition; Synergy synergy[3]; const char* name; const char* ability; const char* drawback; };',
            'inline int Frames(int ms,int fps) {return (ms*fps+999)/1000;}',
            'static const Profile Profiles[64]={']
    for row in authored:
        synergy=', '.join('{Action::%s,%d,%d}'%(row[h]['action'],row[h]['power'],round(row[h]['cooldown_seconds']*1000)) for h in ['robin','diana','max'])
        header.append(' {%d,%d,%d,%d,%d,%d,Action::%s,%d,%d,Condition::%s,{%s},%s,%s,%s},'%(
            row['id'],row['npc_id'],row['cols'],row['rows'],round(row['attack_seconds']*1000),row['attack_percent'],
            row['action'],round(row['ability_seconds']*1000),row['power'],row['condition'],synergy,
            quoted(row['name']),quoted(row['ability']),quoted(row['drawback'])))
    header += ['};','inline const Profile* Get(int id) {return id>=0 && id<64?&Profiles[id]:nullptr;}',
               'inline bool Prototype(const Profile& p) {return p.id==36 || p.id==45 || p.id==57;}','}']
    (ROOT/'Classes/Data/AllyBalanceData.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
    out=ROOT/'reports/hero_allies_64'
    (out/'balance.json').write_text(json.dumps(authored,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    lines=['# 동료 64종 적용 밸런스 v1', '',
           '기존 ID·이름·이미지·3단계 스킬을 유지하는 첫 플레이테스트 기준입니다. 원본 공격력에 공격 배율을 곱하며 최종 DPS는 기존 성장 수치에도 영향을 받습니다.', '',
           '영웅 연계: 로빈은 검 명중, 디아나는 사격, 맥스는 실제 귀환 완료. 표의 효과는 각자 최소 간격을 가지며 파생 공격은 연계를 재발동하지 않습니다.', '',
           '|ID|동료 / 고유 능력|공격 간격 / 배율|점유|능력 / 주기 / 수치|조건·제약|로빈 연계|디아나 연계|맥스 연계|',
           '|---|---|---|---|---|---|---|---|---|']
    def syn(r,h):
        s=r[h];return f"{effect(s['action'],s['power'])} / {s['cooldown_seconds']:g}초"
    for r in authored:
        lines.append(f"|{r['id']}|{r['name']} — {r['ability']}|{r['attack_seconds']:g}초 / {r['attack_percent']}%|{r['cols']}×{r['rows']}|{effect(r['action'],r['power'])} / {r['ability_seconds']:g}초|{r['drawback']}|{syn(r,'robin')}|{syn(r,'diana')}|{syn(r,'max')}|")
    lines+=['','효과명·수치 단위, 상태이상 상한, 발동 조건과 예외는 [런타임 규칙](BALANCE_RULES.md)을 확인하세요.','']
    (out/'BALANCE.md').write_text('\n'.join(lines),encoding='utf-8')
    print('PASS 64 authored abilities, stable IDs/assets/skills, grid sizes, timing ranges and 192 hero synergies')

if __name__=='__main__': main()
